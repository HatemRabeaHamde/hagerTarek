// Inlines every image from /public/images as a data URI (artifact pages cannot fetch files).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const pub = path.resolve(import.meta.dirname, '../../public');
const lines = ['// Generated by gen-data-uris.mjs — do not edit.', 'export const DATA_URIS: Record<string, string> = {'];
for (const dir of readdirSync(path.join(pub, 'images'))) {
  for (const file of readdirSync(path.join(pub, 'images', dir)).filter((f) => f.endsWith('.webp'))) {
    const b64 = readFileSync(path.join(pub, 'images', dir, file)).toString('base64');
    lines.push(`  '/images/${dir}/${file}': 'data:image/webp;base64,${b64}',`);
  }
}
lines.push('};');
writeFileSync(path.resolve(import.meta.dirname, 'src/dataUris.gen.ts'), lines.join('\n'));
